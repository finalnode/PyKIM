"""The famous opening of Beethoven's Für Elise."""


from pykim import *


part_a = [
    ("E5", 1), ("D#5", 1), ("E5", 1), ("D#5", 1),
    ("E5", 1), ("B4", 1), ("D5", 1), ("C5", 1), ("A4", 3),
    ("C4", 1), ("E4", 1), ("A4", 1), ("B4", 3),
    ("E4", 1), ("G#4", 1), ("B4", 1), ("C5", 3),
        ("E4", 1), ("E5", 1), ("D#5", 1), ("E5", 1), ("D#5", 1),
    ("E5", 1), ("B4", 1), ("D5", 1), ("C5", 1), ("A4", 3),
    ("C4", 1), ("E4", 1), ("A4", 1), ("B4", 3),
    ("E4", 1), ("C5", 1), ("B4", 1), ("A4", 4),
]

part_b = [
    ("E4", 1), ("E5", 1), ("D#5", 1), ("E5", 1), ("D#5", 1),
    ("E5", 1), ("B4", 1), ("D5", 1), ("C5", 1), ("A4", 3),
    ("C4", 1), ("E4", 1), ("A4", 1), ("B4", 3),
    ("E4", 1), ("C5", 1), ("B4", 1), ("A4", 4),
]

for note, beats in part_a:
    play_tone(note, beats)


for note, beats in part_b:
    play_tone(note, beats)

run()
